import os
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from reportlab.lib import colors
from reportlab.platypus import Table, TableStyle
from datetime import datetime
import uuid

INVOICE_DIR = "invoices"
os.makedirs(INVOICE_DIR, exist_ok=True)

def generate_invoice(customer_name: str, amount: int):

    invoice_id = "INV-" + str(uuid.uuid4())[:6]
    filename = f"{invoice_id}.pdf"
    file_path = os.path.join(INVOICE_DIR, filename)

    c = canvas.Canvas(file_path, pagesize=A4)
    width, height = A4

    # ---------------- HEADER ----------------
    c.setFont("Helvetica-Bold", 20)
    c.drawString(50, height - 50, "Bharat Biz Agent 🇮🇳")

    c.setFont("Helvetica", 10)
    c.drawString(50, height - 70, "Digital Business Assistant for Indian Vendors")
    c.drawString(50, height - 85, "Email: support@bharatbiz.in")
    c.drawString(50, height - 100, "Phone: +91 9876543210")

    # ---------------- INVOICE INFO ----------------
    c.setFont("Helvetica-Bold", 14)
    c.drawString(400, height - 50, "INVOICE")

    c.setFont("Helvetica", 10)
    c.drawString(400, height - 70, f"Invoice ID: {invoice_id}")
    c.drawString(400, height - 85, f"Date: {datetime.now().strftime('%d-%m-%Y')}")

    # ---------------- BILL TO ----------------
    c.setFont("Helvetica-Bold", 12)
    c.drawString(50, height - 140, "Bill To:")

    c.setFont("Helvetica", 11)
    c.drawString(50, height - 160, customer_name)

    # ---------------- TABLE ----------------
    data = [
        ["Description", "Amount (₹)"],
        ["Service Charges", str(amount)]
    ]

    table = Table(data, colWidths=[300, 100])
    table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.lightgrey),
        ('GRID', (0,0), (-1,-1), 1, colors.grey),
        ('ALIGN', (1,1), (-1,-1), 'RIGHT')
    ]))

    table.wrapOn(c, width, height)
    table.drawOn(c, 50, height - 250)

    # ---------------- TOTAL ----------------
    c.setFont("Helvetica-Bold", 12)
    c.drawString(350, height - 280, f"Total: ₹{amount}")

    # ---------------- FOOTER ----------------
    c.setFont("Helvetica-Oblique", 9)
    c.drawString(50, 50, "Generated by Bharat Biz Agent - AI Powered Billing Assistant")

    c.save()

    return invoice_id, file_path
